import assert from 'node:assert/strict';
const base = process.env.GATE_ROUTER_BASE;
const origin = 'https://' + process.env.AW_DOMAIN;
const call = (path, init = {}) => fetch(new URL(path, base + '/'), { redirect: 'manual', ...init });
const check = (name, ok) => { assert.ok(ok, name); console.log('PASS ' + name); };
let r = await call('/', { headers: { accept: 'text/html' } });
check('Caddy root redirects without native challenge', r.status === 303 && r.headers.get('location') === '/__gate/login' && !r.headers.has('www-authenticate'));
for (const path of ['/api/content', '/build-info.json', '/api/dungeons/00000000-0000-0000-0000-000000000000/live']) {
  r = await call(path);
  check('unauthorized protected route ' + path, r.status === 401 && !r.headers.has('www-authenticate'));
}
r = await call('/api/content', { headers: { 'X-Forwarded-Uri': '/api/health', 'X-Forwarded-Method': 'GET', 'X-Forwarded-For': '127.0.0.1' } });
check('spoofed forwarded headers cannot bypass gate', r.status === 401);
r = await call('/api/health');
check('monitoring remains public', r.status === 200 && (await r.json()).ok);
r = await call('/__gate/login');
check('Caddy serves form-compatible referrer policy', r.headers.get('referrer-policy') === 'strict-origin');
const html = await r.text(), csrf = html.match(/name="csrf" value="([^"]+)"/)[1];
const cookie = r.headers.getSetCookie()[0].split(';')[0];
r = await call('/__gate/login', { method: 'POST', headers: { origin, cookie, 'content-type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams({ username: process.env.GATE_TEST_USER, password: process.env.GATE_TEST_PASSWORD, csrf }) });
check('form POST reaches real bcrypt verifier', r.status === 303);
const session = r.headers.getSetCookie().find(x => x.startsWith('__Host-aw_gate=')).split(';')[0];
r = await call('/', { headers: { cookie: session } });
const app = await r.text();
check('cookie opens actual game HTML', r.status === 200 && app.includes('<script'));
const asset = app.match(/src="([^"]+\.js)"/)[1];
r = await call(asset);
check('actual JS asset protected', r.status === 401);
r = await call(asset, { headers: { cookie: session } });
check('cookie opens actual JS asset', r.status === 200 && (r.headers.get('content-type') ?? '').includes('javascript'));
r = await call('/api/content', { headers: { cookie: session } });
check('cookie opens actual content API', r.status === 200 && (r.headers.get('content-type') ?? '').includes('json'));
r = await call('/api/content', { headers: { authorization: 'Basic ' + Buffer.from(process.env.GATE_TEST_USER + ':' + process.env.GATE_TEST_PASSWORD).toString('base64') } });
check('existing Basic Auth clients remain compatible', r.status === 200);
console.log('Caddy integration passed');
// Issuance is never routed through the public Caddy listener.
r = await call('/issue-invite', { method: 'POST', headers: { authorization: 'Bearer ' + process.env.AW_GATE_SESSION_KEY } });
check('internal invitation issuer is not publicly reachable', r.status === 401);
r = await fetch('http://127.0.0.1:8080/issue-invite', { method: 'POST', headers: { authorization: 'Bearer ' + process.env.AW_GATE_SESSION_KEY } });
assert.equal(r.status, 200);
const invite = new URL((await r.json()).url);
r = await call(invite.pathname + invite.search);
check('public invitation GET redirects without native auth', r.status === 303 && !r.headers.has('www-authenticate') && r.headers.get('location') === '/');
const inviteCookie = r.headers.getSetCookie()[0].split(';')[0];
r = await call('/', { headers: { cookie: inviteCookie } });
check('invitation cookie reaches actual game page', r.status === 200 && (await r.text()).includes('<script'));
r = await call('/api/content', { headers: { cookie: inviteCookie } });
check('invitation cookie reaches actual content API', r.status === 200);
r = await call(invite.pathname + invite.search);
check('public invitation replay rejected', r.status === 410 && !r.headers.has('set-cookie'));
