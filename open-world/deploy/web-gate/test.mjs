// Runs against a REAL Caddy bcrypt verifier; never substitutes a mock verifier.
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { createGate } from './server.mjs';
const verifier = process.env.GATE_TEST_VERIFIER;
if (!verifier || !process.env.GATE_TEST_PASSWORD) throw Error('Real Caddy verifier and test credentials required');
let clock = Date.now();
const options = { origin: 'https://gate-test.example', secret: randomBytes(32).toString('hex'), credentialHash: 'test-credential-revision', verifier, now: () => clock };
const server = createGate(options);
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const base = 'http://127.0.0.1:' + server.address().port;
const call = (path, init = {}) => fetch(base + path, { redirect: 'manual', ...init });
let count = 0;
const check = (name, condition) => { assert.ok(condition, name); count++; console.log('PASS ' + name); };
try {
  let r = await call('/__gate/login');
  const html = await r.text();
  const csrf = html.match(/name="csrf" value="([^"]+)"/)[1];
  const csrfCookie = r.headers.getSetCookie()[0].split(';')[0];
  check('public HTML form without Basic challenge', r.status === 200 && !r.headers.has('www-authenticate') && html.includes('type="password"'));
  check('form referrer policy preserves same-origin POST Origin', r.headers.get('referrer-policy') === 'strict-origin');
  r = await call('/issue-invite', { method: 'POST' });
  check('invitation issuance requires internal authorization', r.status === 403);
  const issue = async () => {
    const response = await call('/issue-invite', { method: 'POST', headers: { authorization: 'Bearer ' + options.secret } });
    assert.equal(response.status, 200);
    return new URL((await response.json()).url);
  };
  let invitation = await issue();
  r = await call(invitation.pathname + invitation.search);
  const inviteSession = r.headers.getSetCookie()[0]?.split(';')[0];
  check('invitation creates session without credentials or form POST', r.status === 303 && !!inviteSession && r.headers.get('referrer-policy') === 'no-referrer');
  r = await call('/verify', { headers: { cookie: inviteSession } });
  check('invitation session grants protected access', r.status === 200);
  r = await call(invitation.pathname + invitation.search);
  check('invitation cannot be redeemed twice', r.status === 410 && !r.headers.has('set-cookie'));
  invitation = await issue();
  const concurrent = await Promise.all([call(invitation.pathname + invitation.search), call(invitation.pathname + invitation.search)]);
  check('concurrent redemption has exactly one winner', concurrent.map(x => x.status).sort().join(',') === '303,410');
  invitation = await issue(); clock += 1801_000;
  r = await call(invitation.pathname + invitation.search);
  check('expired invitation rejected', r.status === 410 && !r.headers.has('set-cookie'));
  clock -= 1801_000;
  r = await call('/__gate/invite?token=' + 'a'.repeat(43));
  check('forged invitation rejected', r.status === 410 && !r.headers.has('set-cookie'));
  const headers = { origin: options.origin, 'content-type': 'application/x-www-form-urlencoded', cookie: csrfCookie };
  const form = { username: process.env.GATE_TEST_USER, password: process.env.GATE_TEST_PASSWORD, csrf };
  const post = (changes = {}, overrides = {}) => call('/__gate/login', { method: 'POST', headers: { ...headers, ...overrides }, body: new URLSearchParams({ ...form, ...changes }) });
  r = await post({}, { origin: 'https://untrusted.example' });
  check('cross-origin login rejected', r.status === 403);
  r = await post({}, { origin: 'null' });
  check('opaque Origin remains rejected', r.status === 403);
  r = await post({ csrf: 'forged' });
  check('forged CSRF rejected', r.status === 403);
  r = await post({ password: 'deliberately-invalid' });
  check('wrong password rejected without native challenge', r.status === 401 && !r.headers.has('www-authenticate') && !(r.headers.get('set-cookie') ?? '').includes('__Host-aw_gate='));
  r = await post();
  const set = r.headers.getSetCookie().find(x => x.startsWith('__Host-aw_gate='));
  check('real Caddy credential accepted', r.status === 303 && r.headers.get('location') === '/' && !!set);
  check('secure cookie attributes', ['HttpOnly', 'Secure', 'SameSite=Lax', 'Path=/', 'Max-Age=43200'].every(x => set.includes(x)) && !set.includes('Domain='));
  const session = set.split(';')[0];
  r = await call('/verify', { headers: { cookie: session } });
  check('valid session accepted', r.status === 200);
  r = await call('/verify', { headers: { cookie: session + 'x' } });
  check('tampered session rejected', r.status === 401);
  r = await call('/verify', { headers: { accept: 'text/html', 'x-forwarded-method': 'GET', 'x-forwarded-uri': '/' } });
  check('anonymous navigation redirects to HTML login', r.status === 303 && r.headers.get('location') === '/__gate/login');
  r = await call('/verify', { headers: { accept: 'text/html', 'x-forwarded-method': 'POST', 'x-forwarded-uri': '/api/login' } });
  check('anonymous API cannot redirect into success', r.status === 401);
  clock += 43201_000;
  r = await call('/verify', { headers: { cookie: session } });
  check('expired session rejected', r.status === 401);
  clock -= 43201_000;
  const rotated = createGate({ ...options, credentialHash: 'rotated' });
  await new Promise(resolve => rotated.listen(0, '127.0.0.1', resolve));
  try { r = await fetch('http://127.0.0.1:' + rotated.address().port + '/verify', { headers: { cookie: session } }); check('credential rotation revokes sessions', r.status === 401); }
  finally { rotated.closeAllConnections(); await new Promise(resolve => rotated.close(resolve)); }
  r = await call('/__gate/logout', { method: 'POST', headers: { origin: options.origin, cookie: session } });
  check('logout clears browser access cookie', r.status === 303 && r.headers.get('set-cookie').includes('Max-Age=0'));
  for (let i = 0; i < 11; i++) r = await post({ password: 'invalid' });
  check('repeated attempts rate limited', r.status === 429 && r.headers.get('retry-after') === '60');
  console.log(JSON.stringify({ passed: count }));
} finally { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); }
