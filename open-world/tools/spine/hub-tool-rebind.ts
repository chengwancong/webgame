/** Rebind only repaired analysis/harness fingerprints. Never derives numbers. */
import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve,relative,isAbsolute,dirname} from 'node:path';
import {createHash} from 'node:crypto';
import {versions} from '../../packages/contracts/index.ts';
import {hubRewardPlanSchema,hubRewardEvidenceSchema} from './hub-reward-schema.ts';
import {hubPlanHash,hubRewardSourceHashes} from './hub-rewards.ts';
import {assertHubAppliedWorkbooks,hubRuntimeNumbersHash} from './hub-plan-integrity.ts';
const [input,output,probePath]=process.argv.slice(2);
assert(input&&output&&probePath,'Provide original plan, new .runtime plan path and actual post-apply combat evidence.');
const inside=relative(resolve('.runtime'),resolve(output));
assert(!isAbsolute(inside)&&!inside.startsWith('..'),'Receipts must remain in .runtime.');
const read=async(p:string)=>JSON.parse(await readFile(p,'utf8'));
const old=hubRewardPlanSchema.parse(await read(input)),probe=hubRewardEvidenceSchema.parse(await read(probePath));
assert.equal(old.phase,'derive','Cannot rebind a correction or grant another correction.');
assert.deepEqual(old.versions,versions);assert.deepEqual(probe.versions,versions);
const oldHash=hubPlanHash(old),runtimeNumbersHash=await hubRuntimeNumbersHash();
assert.equal(probe.planHash,oldHash);assert.equal(probe.runtimeNumbersHash,runtimeNumbersHash);
const current=await hubRewardSourceHashes();
assert.deepEqual(Object.keys(current).sort(),Object.keys(old.sourceHashes).sort());
const changed=Object.keys(current).filter(f=>current[f]!==old.sourceHashes[f]);
assert(changed.length>0,'No tool repair to bind.');
assert(changed.every(f=>['tools/spine/hub-rewards.ts','tools/hub-autopilot.ts','tools/spine/hub-reward-schema.ts','tools/spine/hub-plan-integrity.ts','tools/hub-reward-apply.mjs'].includes(f)),'Game source or unrelated tooling drift; refuse rebind.');
await assertHubAppliedWorkbooks(oldHash);
const next=hubRewardPlanSchema.parse({...old,sourceHashes:current});
const signature=(p:typeof old)=>createHash('sha256').update(JSON.stringify({...p,sourceHashes:{}})).digest('hex');
assert.equal(signature(old),signature(next),'Any change beyond sourceHashes is forbidden.');
const nextHash=hubPlanHash(next),oldManifest=await read(`.runtime/b4/workbooks/${oldHash}/applied-workbooks.json`);
const receipt={fromPlanHash:oldHash,toPlanHash:nextHash,unchangedPlanSignature:signature(old),runtimeNumbersHash,versions,changedToolSources:changed.map(file=>({file,before:old.sourceHashes[file],after:current[file]})),originalPlan:input,originalMeasurement:probePath,appliedFiles:oldManifest.files};
await mkdir(dirname(resolve(output)),{recursive:true});
await writeFile(output,JSON.stringify(next,null,2)+'\n',{flag:'wx'});
await writeFile(output+'.rebind.json',JSON.stringify(receipt,null,2)+'\n',{flag:'wx'});
await mkdir(`.runtime/b4/workbooks/${nextHash}`,{recursive:true});
await writeFile(`.runtime/b4/workbooks/${nextHash}/applied-workbooks.json`,JSON.stringify({...oldManifest,planHash:nextHash,originalAppliedPlanHash:oldHash,metadataRebindReceipt:output+'.rebind.json'},null,2)+'\n',{flag:'wx'});
await assertHubAppliedWorkbooks(nextHash);
console.log(JSON.stringify({oldHash,nextHash,unchangedPlanSignature:signature(old),changedToolSources:changed}));
